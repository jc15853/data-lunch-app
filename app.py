        st.warning(f"선택한 알레르기 번호: {selected_allergies}")
        
        def check_allergy(row_allergies):
            return any(code in row_allergies for code in selected_allergies)

        danger_df = df[df['알레르기'].apply(check_allergy)]
        
        st.write(f"⚠️ 9월 중 주의해야 할 급식일은 총 **{len(danger_df)}일**입니다.")
